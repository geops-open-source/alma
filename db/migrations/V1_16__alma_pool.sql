create table alma.pool (
    pool_id integer not null generated by default as identity,
    bezeichnung text not null,
    bemerkungen text,
    erfassungs_datum timestamp without time zone default now(),
    erfasser text,
    mutations_datum timestamp without time zone,
    mutierer text,
    constraint pk_pool primary key (pool_id),
    constraint uq_pool_art_bezeichnung unique (bezeichnung)
);

