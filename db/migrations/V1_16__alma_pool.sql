create table alma.vfl_pool (
    vfl_pool_id integer not null generated by default as identity,
    pool_id integer not null,
    vfl_id integer not null,
    erfassungs_datum timestamp without time zone default now(),
    erfasser text,
    mutations_datum timestamp without time zone,
    mutierer text,
    constraint pk_vfl_pool primary key (vfl_pool_id),
    constraint uq_vfl_pool_pool_id_vfl_id unique (pool_id, vfl_id),
    constraint fk_pool_vfl_pool_vfl_id foreign key (pool_id) references alma.pool(pool_id) on delete cascade on update cascade
);

