create table alma_admin.settings (
    id integer not null generated by default as identity,
    key varchar not null,
    value jsonb not null,
    value_schema jsonb not null,
    category varchar not null,
    constraint uq_settings_key_category unique (key, category),
    constraint ck_settings_category check (category = 'ADMIN' or category = 'GENERAL'),
