CREATE TABLE alma_admin.auth_user (
    id BIGSERIAL NOT NULL,
    sub VARCHAR NOT NULL,
    username VARCHAR NOT NULL,
    role_id BIGINT,
    email VARCHAR NOT NULL,
    first_name VARCHAR DEFAULT '' NOT NULL,
    last_name VARCHAR DEFAULT '' NOT NULL,
    is_sachbearbeitung BOOLEAN DEFAULT false NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    CONSTRAINT pk_auth_user_id PRIMARY KEY (id),
    CONSTRAINT uq_auth_user_email UNIQUE (email),
    CONSTRAINT uq_auth_user_username UNIQUE (username),
    CONSTRAINT uq_auth_user_sub UNIQUE (sub),
    CONSTRAINT fk_auth_role_auth_user_role_id FOREIGN KEY(role_id) REFERENCES alma_admin.auth_role (id) ON DELETE SET NULL
);

