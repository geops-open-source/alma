create table alma_admin.oidc_session (
    id integer not null generated by default as identity,
    session_key varchar not null,
    expires_at timestamp with time zone not null,
    token varchar not null,
    user_id bigint not null,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    constraint pk_oidc_session_id primary key (id),
    constraint uq_oidc_session_session_key unique (session_key),
    constraint fk_oidc_session_auth_user_user_id foreign key (user_id) references alma_admin.auth_user (id) on delete cascade,
    constraint ck_oidc_session_session_key_length check (length(session_key) >= 32)
);

