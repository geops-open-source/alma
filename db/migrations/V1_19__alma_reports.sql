comment on column alma_export.report_report_sql_query.report_sql_query_id is 'Foreign Key zur Sql Query.';

create table alma_export.report_param (
    param_id integer not null generated by default as identity,
    report_id integer not null,
    name text not null,
    type text not null,
    sort_key integer,
    constraint pk_report_param_param_id primary key (param_id),
    constraint uq_report_param_name_report_id unique (name, report_id),
    constraint ck_report_param_type check (type = 'INTEGER' or type = 'BOOL' or type = 'TEXT' or type = 'DATE'),
    constraint fk_report_report_param foreign key (report_id) references alma_export.report (report_id)
);

