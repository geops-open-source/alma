comment on column alma_export.report_sql_query.name is 'Eineindeutiger Name fuer die Query.';
comment on column alma_export.report_sql_query.description is 'Beschreibung der Query.';
comment on column alma_export.report_sql_query.query is 'Eigentliche Query.';


create table alma_export.report_report_sql_query (
    report_id integer not null,
    report_sql_query_id integer not null,
    constraint pk_report_report_sql_query_id_report_id primary key (report_sql_query_id, report_id),
    constraint fk_report_report_report_report_sql_query foreign key (report_id) references alma_export.report (report_id),
    constraint fk_report_report_sql_query_report_report_sql_query foreign key (report_sql_query_id) references alma_export.report_sql_query (report_sql_query_id)
);

comment on table alma_export.report_report_sql_query is 'Tabelle zum Mapping von Sql Queries zu Reporten.';
