create table alma.wf_config (
    wf_config_id integer not null generated by default as identity,
    key uuid not null,
    workflow_id integer references alma.wf_config(wf_config_id),
    title text not null,
    "type" varchar(100) not null,
    version integer not null default 1,
    time_period integer,
    name text,
    -- Felder Typ workflow
    start_task_id integer references alma.wf_config(wf_config_id),
    -- Felder Typ workflow und task (nur eigenständig)
    min_per_entity integer not null default 0,
    max_per_entity integer,
    -- Felder Typ task
    events jsonb,
    is_start_task boolean,
    -- Felder Typ formular
    fields jsonb,
    -- Felder Type dokument, formular
    is_optional boolean,
    constraint pk_workflow_workflow_id primary key (wf_config_id),
    constraint uq_workflow_key unique (key),
    constraint uq_workflow_id_name unique (workflow_id, name),
    constraint check_type check ("type" in ('workflow', 'task', 'form', 'document'))
);

