create table alma.wf_node (
    wf_node_id integer not null generated by default as identity,
    title text not null,
    "type" varchar(100) not null,
    wf_config_id integer references alma.wf_config(wf_config_id),
    version integer,
    parent_id integer references alma.wf_node(wf_node_id),
    next_node_id integer references alma.wf_node(wf_node_id),
    is_moveable boolean not null default false,
    status text not null default 'started',
    started_at timestamp without time zone not null default now(),
    finished_at timestamp without time zone,
    deadline timestamp without time zone,
    entity_id integer not null references alma.vflz(vflz_id),
    data jsonb not null default '{}'::jsonb,
    note text,
    form_config jsonb,
    form_data jsonb,
    document_ref varchar(255),
    is_public boolean default false,
    erfassungs_datum timestamp without time zone default now(),
    erfasser text,
    mutations_datum timestamp without time zone,
    mutierer text,
    constraint check_status check (status in ('started', 'finished', 'skipped', 'inactive')),
    constraint pk_wf_node_wf_node_id primary key (wf_node_id),
    constraint check_type check ("type" in ('workflow', 'task', 'form', 'document', 'note')),
    constraint check_workflow_version check ((wf_config_id is null and version is null) or (wf_config_id is not null and version is not null)),
    constraint check_deadline_status check ((status = 'inactive' and deadline is null) or (status != 'inactive')),
    -- next_node_id can only be not null if wf_config_id is not null.
    constraint check_next_node_id check ((wf_config_id is null and next_node_id is null) or wf_config_id is not null)
);

