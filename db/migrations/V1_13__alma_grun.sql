create table alma.h_nb (
    h_nb_id varchar not null,
    bezeichnung text,
    wkb_geometry geometry(MULTIPOLYGON, 2056),
    erfassungs_datum timestamp without time zone default now(),
    erfasser text,
    mutations_datum timestamp without time zone default now(),
    mutierer text,
    constraint pk_h_nb primary key (h_nb_id)
);
create index idx_h_nb_wkb_geometry on alma.h_nb using gist (wkb_geometry);

