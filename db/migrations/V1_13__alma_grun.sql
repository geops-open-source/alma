create table alma.grun (
    grun_id integer not null generated by default as identity,
    h_gem_id integer not null,
    h_nb_id varchar,
    gb_nummer varchar not null,
    egrid varchar,
    h_grun_status integer not null default 26000,
    c_grun_status varchar not null default '1',
    wkb_geometry public.geometry(MULTIPOLYGON, 2056) NULL,
    erfassungs_datum timestamp without time zone default now(),
    erfasser text,
    mutations_datum timestamp without time zone default now(),
    mutierer text,
    constraint enforce_dims_wkb_geometry check ((st_ndims(wkb_geometry) = 2)),
    constraint enforce_srid_wkb_geometry check ((st_srid(wkb_geometry) = 2056)),
    -- when c_status = '1' then h_nb_id must not be NULL
    --TODO: after import foreign parcel data add the following lines
    -- constraint enforce_h_nb_id_not_null check (not c_grun_status = '1' or h_nb_id is not null),
    constraint pk_grun_grun_id primary key (grun_id)
);
create index idx_grun_wkb_geometry on alma.grun using gist (wkb_geometry);
-- Make sure egrid and h_nb_id+gb_nummer are unique among rows with c_status = '1' (current)
create unique index iq_grun_egrid_is_current on alma.grun using btree (egrid) where c_grun_status = '1';
create unique index iq_grun_h_n_bid_gb_nummer_is_current on alma.grun using btree (h_nb_id, gb_nummer) where c_grun_status = '1';

