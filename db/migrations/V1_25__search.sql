comment on column alma_admin.search.user_id is 'Erfasser';
comment on column alma_admin.search.is_shared is 'Gibt an ob Suche geteilt wird oder nicht';
comment on column alma_admin.search.query is 'Suchabfrage';
comment on column alma_admin.search.fields is 'Ausgabefelder der Suche';
comment on column alma_admin.search.is_grouped is 'Gibt an ob Suchergebnisse gruppiert werden sollen.';

create index ix_pk_search_search_id on alma_admin.search using btree(search_id);
