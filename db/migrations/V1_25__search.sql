create table alma_admin.search (
    search_id integer not null generated by default as identity,
    is_temporary boolean not null default false,
    name text not null,
    user_id integer not null,
    is_shared boolean not null default false,
    query jsonb not null,
    fields jsonb not null,
    sort_by jsonb not null,
    is_grouped boolean not null,
    constraint pk_search_search_id primary key (search_id),
    constraint fk_auth_user_search_user_id foreign key(user_id) references alma_admin.auth_user(id) on delete cascade,
    constraint uq_search_user_id_search_name unique (user_id, name),
    constraint chk_search_is_temporary_is_shared check ((is_temporary is true and is_shared is not true) or (is_temporary is false))
);

