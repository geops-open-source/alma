comment on column alma.bemgrp.sort is 'Sortierreihenfolge, wenn mehrere Bemerkungen aufgelistet sind';
comment on column alma.bemgrp.public is 'Filterkriterium zur Anzeige in öffentlichen Daten. Kommentare die public=true haben werden in den öffentlichen Reporten angezeigt';
comment on column alma.bemgrp.key_column is 'Foreign key: Spalte zur referenz Tabelle';
comment on column alma.bemgrp.rel_name is 'Foreign key: referenz Tabelle';
comment on column alma.bemgrp.multiple is 'Kennzeichen, um festzustellen, ob mehrere Anmerkungen pro Entität unterstützt werden';
comment on column alma.bemgrp.erfassungs_datum is 'Datum der Erfassung';
comment on column alma.bemgrp.erfasser is 'Erfasser';
comment on column alma.bemgrp.mutations_datum is 'Datum der letzten Aenderung';
comment on column alma.bemgrp.mutierer is 'Bearbeiter der letzten Aenderung';

create index idx_bemgrp_bemgrp on alma.bemgrp using btree (bemgrp);



