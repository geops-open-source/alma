create table alma.bemgrp (
    bemgrp_id integer not null generated by default as identity,
    bemgrp character varying(50),
    title character varying(50),
    description character varying,
    sort integer,
    public boolean default false not null,
    key_column character varying(50) not null,
    rel_name character varying(50) not null,
    multiple boolean default false not null,
    erfassungs_datum timestamp without time zone default now(),
    erfasser text,
    mutations_datum timestamp without time zone,
    mutierer text,
    constraint pk_bemgrp_bemgrp_id primary key (bemgrp_id),
    constraint uq_bemgrp_bemgrp unique (bemgrp)
);

