comment on column alma_external.wfs_cache.ort is 'Ort';
comment on column alma_external.wfs_cache.h_gem_id is 'Gemeinde ID.';
comment on column alma_external.wfs_cache.gemeinde_name is 'Name der Gemeinde.';
comment on column alma_external.wfs_cache.bfs_nummer is 'BFS Nummer der Gemeinde.';
comment on column alma_external.wfs_cache.h_nb_id is 'Parzelle: Nummierungsbereich';
comment on column alma_external.wfs_cache.egrid is 'Parzelle: EGRID';
comment on column alma_external.wfs_cache.gb_nummer is 'Parzelle: Grundbuchsnummer';
comment on column alma_external.wfs_cache.gws_zone is 'Gewaesserschutzzone.';
