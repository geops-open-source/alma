create table alma_external.wfs_cache (
    wfs_cache_id integer not null generated by default as identity,
    wkb_geometry public.geometry not null,
    postleitzahl character varying(8),
    ort character varying(100),
    h_gem_id int,
    gemeinde_name text,
    bfs_nummer integer,
    h_nb_id text,
    egrid text,
    gb_nummer text,
    gws_zone text,
    gws_bereich text,
    wfs_service_name text not null,
    created_at timestamp without time zone not null default now(),
    constraint pk_wfs_cache primary key (wfs_cache_id),
    constraint enforce_srid_wkb_geometry check ((public.st_srid(wkb_geometry) = 2056))
);

create index ix_wfs_cache_wfs_cache_id on alma_external.wfs_cache using btree(wfs_cache_id);
create index ix_wfs_cache_geometry on alma_external.wfs_cache using gist(wkb_geometry);

